"""The LibreView export, in the layouts different account languages produce.
All values are made up; real exports never go into the repository."""
from datetime import datetime
from zoneinfo import ZoneInfo

import pytest

from libre_mcp import csv_import

BERLIN = ZoneInfo("Europe/Berlin")

GERMAN = (
    "﻿Glukosewerte,Erstellt am,28-09-2026 08:00 UTC,Erstellt von,Max Muster\n"
    "Gerät,Seriennummer,Gerätezeitstempel,Aufzeichnungstyp,Glukosewert-Verlauf mg/dL,"
    "Glukose-Scan mg/dL,Nicht numerisches schnellwirkendes Insulin,Notizen\n"
    "FreeStyle Libre 3,ABC,27-09-2026 07:02,0,112,,,\n"
    "FreeStyle Libre 3,ABC,27-09-2026 07:07,1,,115,,\n"
    "FreeStyle Libre 3,ABC,27-09-2026 07:17,0,118,,,\n"
    "FreeStyle Libre 3,ABC,27-09-2026 07:20,6,,,,Laufen\n"
    "FreeStyle Libre 3,ABC,25-10-2026 02:30,0,90,,,\n"
)

ENGLISH_US = (
    "Glucose Data,Generated on,09-28-2026 08:00 UTC,Generated by,Max Muster\n"
    "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,"
    "Scan Glucose mg/dL,Notes\n"
    "FreeStyle Libre 3,ABC,09-27-2026 07:02,0,112,,\n"
    "FreeStyle Libre 3,ABC,09-13-2026 07:02,0,100,,\n"
)

MMOL = (
    "Glukosewerte;Erstellt am;28.09.2026 08:00 UTC;Erstellt von;Max Muster\n"
    "Gerät;Seriennummer;Gerätezeitstempel;Aufzeichnungstyp;Glukosewert-Verlauf mmol/L;"
    "Glukose-Scan mmol/L\n"
    "FreeStyle Libre 3;ABC;27.09.2026 07:02;0;6,2;\n"
)


def at(y, mo, d, h, mi):
    return int(datetime(y, mo, d, h, mi, tzinfo=BERLIN).timestamp())


def test_german_export():
    pts = csv_import.parse(GERMAN.encode("utf-8"))
    assert pts == [(at(2026, 9, 27, 7, 2), 112), (at(2026, 9, 27, 7, 17), 118),
                   (at(2026, 10, 25, 2, 30), 90)]          # scans and notes skipped


def test_us_order_is_recognised():
    pts = csv_import.parse(ENGLISH_US.encode("utf-8"))
    assert pts[-1] == (at(2026, 9, 27, 7, 2), 112)


def test_mmol_semicolons_and_decimal_commas():
    assert csv_import.parse(MMOL.encode("cp1252")) == [(at(2026, 9, 27, 7, 2), 112)]


def test_something_else_is_refused():
    with pytest.raises(csv_import.CsvError, match="LibreView"):
        csv_import.parse(b"date,steps\n2026-09-27,12000\n")


def test_an_export_without_history_is_refused():
    head = GERMAN.split("\n")[:2]
    with pytest.raises(csv_import.CsvError, match="no sensor history"):
        csv_import.parse("\n".join(head + ["FreeStyle Libre 3,ABC,27-09-2026 07:07,1,,115,,"])
                         .encode())
